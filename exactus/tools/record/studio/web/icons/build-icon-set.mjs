/** Build `icon-set.js` from the SVG files in this folder.
 *
 * Every icon is drawn on the same 24 by 24 grid, so the page can put each one
 * in the DOM as a real `<svg viewBox="0 0 24 24">` and style it from CSS. Only
 * the shapes are kept: the stroke, fill, width and caps come from the
 * `.studio-icon` rule, so every icon has one weight and follows `currentColor`.
 *
 * Usage:
 *   node icons/build-icon-set.mjs          write ../icon-set.js
 *   node icons/build-icon-set.mjs --check  fail when ../icon-set.js is stale
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { fileURLToPath } from "node:url";
const here = fileURLToPath(new URL(".", import.meta.url));
const target = fileURLToPath(new URL("../icon-set.js", import.meta.url));
const PRESENTATION =
  /\s(?:fill|stroke|stroke-width|stroke-linecap|stroke-linejoin)="[^"]*"/g;

/** The drawing inside one icon file, without presentation attributes.
 * @param {string} name File name.
 * @param {string} source File text.
 * @returns {string} Markup of the shapes.
 * @throws {Error} When the icon is not on the shared 24 by 24 grid.
 */
export const shapesOf = (name, source) => {
  const root = /<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(source);
  if (!root || !/viewBox="0 0 24 24"/.test(root[1] ?? ""))
    throw new Error(`${name} must use viewBox="0 0 24 24".`);
  return (root[2] ?? "")
    .replace(PRESENTATION, "")
    .replace(/\s+/g, " ")
    .replace(/>\s+</g, "><")
    .trim();
};

/** One property of the generated object, written the way the project's
 * formatter writes it, so formatting the file never changes it.
 * @param {string} name Icon name.
 * @param {string} shapes Markup of the shapes.
 * @returns {string} The property line or the wrapped pair of lines.
 */
const entry = (name, shapes) => {
  const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
  const quote = shapes.split('"').length > shapes.split("'").length ? "'" : '"';
  const text = `${quote}${shapes.replaceAll("\\", "\\\\").replaceAll(quote, `\\${quote}`)}${quote}`;
  const line = `  ${key}: ${text},`;
  return line.length <= 80 || key.length <= 4
    ? line
    : `  ${key}:\n    ${text},`;
};

/** The text of `icon-set.js` for the files in this folder.
 * @returns {string}
 */
export const render = () => {
  const names = readdirSync(here)
    .filter(file => file.endsWith(".svg"))
    .sort();
  const lines = names.map(file => {
    const name = file.replace(/\.svg$/, "");
    const shapes = shapesOf(file, readFileSync(`${here}${file}`, "utf8"));
    return entry(name, shapes);
  });
  return `/** The Studio's icons, as the shapes inside a 24 by 24 \`<svg>\`.
 *
 * Generated by \`icons/build-icon-set.mjs\` from \`icons/*.svg\`; edit those
 * files and run the script, not this one. The stroke, fill and weight are not
 * stored here: the \`.studio-icon\` rule sets them for every icon.
 * @type {Readonly<Record<string,string>>}
 */
export const ICONS = Object.freeze({
${lines.join("\n")}
});
`;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== text) {
      process.stderr.write(
        "icon-set.js is out of date. Run build-icon-set.mjs.\n",
      );
      process.exitCode = 1;
    }
  } else writeFileSync(target, text);
}
