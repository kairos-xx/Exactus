"""Shell registration-script renderers.

Each generated script is a thin transport adapter: it captures the
shell's completion context, invokes ``exactus __complete`` with the
normalized request, and maps the returned Unit-Separated records onto
native completion primitives. No CLI semantics live in shell code.

Generated output is deterministic for a fixed ``command_name`` and
``launcher`` and carries a protocol-version marker so stale installs
can be diagnosed.
"""

from __future__ import annotations

from re import sub
from shlex import quote
from typing import Final

from .model import CompletionShell
from .protocol import Constants


def _function_name(*, command_name: str) -> str:
    """Sanitize a command name into a shell function identifier.

    Args:
        command_name: Registered command name.

    Returns:
        Identifier containing only letters, digits and underscores.

    """
    cleaned: str = sub(pattern="[^a-zA-Z0-9_]", repl="_", string=command_name)
    return f"_{cleaned.lstrip('_') or 'tool'}_completion"


def _bash_launcher(*, launcher: tuple[str, ...]) -> str:
    """Quote a launcher argv for POSIX-family shells.

    Args:
        launcher: Executable and fixed arguments.

    Returns:
        Shell-quoted invocation fragment.

    """
    return " ".join(quote(s=word) for word in launcher)


def _powershell_quote(*, word: str) -> str:
    """Quote one argument for PowerShell.

    Args:
        word: Argument text.

    Returns:
        Single-quoted literal.

    """
    return "'" + word.replace("'", "''") + "'"


def _powershell_launcher(*, launcher: tuple[str, ...]) -> str:
    """Render a PowerShell invocation of the launcher.

    Args:
        launcher: Executable and fixed arguments.

    Returns:
        ``& 'exe' 'arg' ...`` fragment.

    """
    return "& " + " ".join(_powershell_quote(word=word) for word in launcher)


def _marker(*, shell: CompletionShell, command_name: str) -> str:
    """Render the deterministic script marker header.

    Args:
        shell: Target shell.
        command_name: Registered command name.

    Returns:
        Comment lines identifying the generator and protocol.

    """
    return (
        f"# Generated by "
        f"{command_name}.\n# Completion protocol: {
            Constants.protocol_version
        }\n# Regenerate with: {command_name} completion {shell.value}\n"
    )


def render_bash(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the Bash registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        Source-able Bash completion code.

    """
    function: str = _function_name(command_name=command_name)
    invoke: str = _bash_launcher(launcher=launcher)
    marker: str = _marker(
        shell=CompletionShell.BASH,
        command_name=command_name,
    )
    return (
        f"{marker}"
        f"{function}"
        f'() {{\n    local cur="${{COMP_WORDS[COMP_CWORD]}}"\n    local -a req'
        f'uest=(\n        "__complete"\n        "--protocol-version='
        f"{Constants.protocol_version}"
        f'"\n        "--shell=bash"\n        "--active-word-index=${{COMP_CWOR'
        f'D}}"\n        "--prefix=${{cur}}"\n    )\n    local word\n    for wo'
        f'rd in "${{COMP_WORDS[@]}}"; do\n        request+=("--word=${{word}}"'
        f")\n    done\n    COMPREPLY=()\n    local line value display descript"
        f"ion kind flags\n    local nospace=0\n    while IFS= read -r line; do"
        f"\n        IFS=$'\\x1f' read -r value display description kind flags "
        f'\\\n            <<< "${{line}}"\n        COMPREPLY+=("${{value}}")\n'
        f'        flags="${{flags:-0}}"\n        if (( (10#${{flags}} & 1) == '
        f"0 )); then\n            nospace=1\n        fi\n    done < <(command "
        f"{invoke}"
        f' "${{request[@]}}" 2>/dev/null)\n    if (( nospace )); then\n       '
        f" compopt -o nospace\n    fi\n}}\ncomplete -F "
        f"{function}"
        f" "
        f"{quote(s=command_name)}"
        f"\n"
    )


def render_zsh(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the Zsh registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        Zsh completion code usable with ``compdef``.

    """
    function: str = _function_name(command_name=command_name)
    invoke: str = _bash_launcher(launcher=launcher)
    return (
        f"#compdef "
        f"{command_name}"
        f"\n"
        f"{_marker(shell=CompletionShell.ZSH, command_name=command_name)}"
        f"{function}"
        f"() {{\n    local -a request spaced spaced_desc nospace nospace_desc "
        f"lines fields\n    local line value display description kind flags\n "
        f'   request=(\n        "__complete"\n        "--protocol-version='
        f"{Constants.protocol_version}"
        f'"\n        "--shell=zsh"\n        "--active-word-index=$((CURRENT - '
        f'1))"\n        "--prefix=${{PREFIX}}"\n    )\n    local word\n    for'
        f' word in "${{words[@]}}"; do\n        request+=("--word=${{word}}")'
        f'\n    done\n    lines=("${{(@f)$(command '
        f"{invoke}"
        f' "${{request[@]}}" 2>/dev/null)}}")\n    for line in "${{lines[@]}}"'
        f"; do\n        fields=()\n        IFS=$'\\x1f' read -rA fields <<< "
        f'"${{line}}"\n        value="${{fields[1]}}"\n        display="${{fie'
        f'lds[2]}}"\n        description="${{fields[3]}}"\n        flags="${{f'
        f'ields[5]:-0}}"\n        if (( (10#${{flags}} & 1) == 0 )); then\n   '
        f'         nospace+=("${{value}}")\n            nospace_desc+=("${{des'
        f'cription}}")\n        else\n            spaced+=("${{value}}")\n    '
        f'        spaced_desc+=("${{description}}")\n        fi\n    done\n   '
        f" (( ${{#spaced[@]}} )) && \\\n        compadd -Q -d spaced_desc -S '"
        f' \' -- "${{spaced[@]}}"\n    (( ${{#nospace[@]}} )) && \\\n        c'
        f"ompadd -Q -d nospace_desc -S '' -- \"${{nospace[@]}}\"\n    return 0"
        f"\n}}\ncompdef "
        f"{function}"
        f" "
        f"{quote(s=command_name)}"
        f"\n"
    )


def _fish_quote(*, word: str) -> str:
    """Quote a Fish argument without POSIX quote concatenation.

    Args:
        word: Literal argument.

    Returns:
        Safely quoted shell text.

    """
    if word and all(char.isalnum() or char in "_./-" for char in word):
        return word
    return "'" + word.replace("\\", "\\\\").replace("'", "\\'") + "'"


def render_fish(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the Fish registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        Fish completion code usable with ``complete``.

    """
    registered: str = _fish_quote(word=command_name)
    function: str = _function_name(command_name=command_name)
    invoke: str = " ".join(_fish_quote(word=word) for word in launcher)
    marker: str = _marker(
        shell=CompletionShell.FISH,
        command_name=command_name,
    )
    return (
        f"{marker}"
        f"function "
        f"{function}"
        f"\n    set -l us (printf '\\x1f')\n    set -l prior (commandline -opc"
        f")\n    set -l active (commandline -ct)\n    set -l request \\\n     "
        f"   __complete \\\n        --protocol-version="
        f"{Constants.protocol_version}"
        f" \\\n        --shell=fish \\\n        --active-word-index=(count $pr"
        f"ior) \\\n        --prefix=$active\n    for word in $prior\n        s"
        f"et -a request --word=$word\n    end\n    set -a request --word=$acti"
        f"ve\n    for line in (command "
        f"{invoke}"
        f" $request 2>/dev/null)\n        set -l fields (string split -- $us $"
        f'line)\n        set -l value $fields[1]\n        set -l description "'
        f'"\n        if test (count $fields) -ge 3\n            set descriptio'
        f'n $fields[3]\n        end\n        if test -n "$description"\n      '
        f"      printf '%s\\t%s\\n' $value $description\n        else\n       "
        f"     printf '%s\\n' $value\n        end\n    end\nend\ncomplete --co"
        f"mmand "
        f"{registered}"
        f" --no-files --arguments '("
        f"{function}"
        f")'\n"
    )


def render_powershell(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the PowerShell registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        PowerShell completion code using the native argument completer.

    """
    invoke: str = _powershell_launcher(launcher=launcher)
    marker: str = _marker(
        shell=CompletionShell.POWERSHELL,
        command_name=command_name,
    )
    quoted_name: str = _powershell_quote(word=command_name)
    variable: str = command_name.replace("-", "_")
    return (
        f"{marker}"
        f"$__"
        f"{variable}"
        f"Completer = {{\n    param(\n        $wordToComplete,\n        $comma"
        f"ndAst,\n        $cursorPosition\n    )\n    $words = [System.Collect"
        f"ions.Generic.List[string]]::new()\n    $prefix = ''\n    $hasActive "
        f"= $false\n    foreach ($element in $commandAst.CommandElements) {{\n"
        f"        if ($element.Extent.StartOffset -gt $cursorPosition) {{ brea"
        f"k }}\n        $raw = $element.Extent.Text\n        $isActive = $elem"
        f"ent.Extent.EndOffset -ge $cursorPosition\n        if ($isActive) {{"
        f"\n            $length = $cursorPosition - $element.Extent.StartOffse"
        f"t\n            $raw = $raw.Substring(0, [Math]::Min($raw.Length, $le"
        f"ngth))\n        }}\n        $tokens = $null\n        $parseErrors = "
        f"$null\n        $parsed = [System.Management.Automation.Language.Pars"
        f"er]::ParseInput(\n            $raw, [ref]$tokens, [ref]$parseErrors"
        f"\n        )\n        $string = $parsed.Find({{\n            param($n"
        f"ode)\n            $node.GetType().Name -in @(\n                'Stri"
        f"ngConstantExpressionAst',\n                'ExpandableStringExpressi"
        f"onAst'\n            )\n        }}, $true)\n        $quoted = $raw.St"
        f"artsWith(\"'\") -or $raw.StartsWith('\"')\n        $value = if (\n  "
        f"          $null -ne $string -and ($quoted -or $raw.Contains('`'))\n "
        f"       ) {{ $string.Value }} else {{ $raw }}\n        $words.Add($va"
        f"lue)\n        if ($isActive) {{\n            $prefix = $value\n     "
        f"       $hasActive = $true\n            break\n        }}\n    }}\n  "
        f"  if (-not $hasActive) {{ $words.Add('') }}\n    $request = [System."
        f"Collections.Generic.List[string]]::new()\n    $request.Add('__comple"
        f"te')\n    $request.Add('--protocol-version="
        f"{Constants.protocol_version}"
        f"')\n    $request.Add('--shell=powershell')\n    $request.Add(\"--a"
        f'ctive-word-index=$($words.Count - 1)")\n    $request.Add("--prefix=$'
        f'prefix")\n    foreach ($word in $words) {{\n        $request.Add("--'
        f'word=$word")\n    }}\n    $output = '
        f"{invoke}"
        f" @request 2>$null\n    foreach ($line in $output) {{\n        $field"
        f"s = $line -split [char]0x1f, 5\n        if ($fields.Count -lt 5) {{ "
        f"continue }}\n        $type = 'ParameterValue'\n        switch ($fiel"
        f"ds[3]) {{\n            'command'   {{ $type = 'Command' }}\n        "
        f"    'option'    {{ $type = 'ParameterName' }}\n            'file'   "
        f"   {{ $type = 'ProviderItem' }}\n            'directory' {{ $type = "
        f"'ProviderContainer' }}\n        }}\n        [System.Management.Autom"
        f"ation.CompletionResult]::new(\n            $fields[0],\n            "
        f"$fields[1],\n            $type,\n            $fields[2]\n        )\n"
        f"    }}\n}}\nRegister-ArgumentCompleter -Native `\n    -CommandName "
        f"{quoted_name}"
        f" `\n    -ScriptBlock $__"
        f"{variable}"
        f"Completer\n"
    )


def render(
    *,
    shell: CompletionShell,
    command_name: str,
    launcher: tuple[str, ...],
) -> str:
    """Dispatch to the shell-specific renderer.

    Args:
        shell: Target shell.
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        The registration script.

    """
    renderers: Final = {
        CompletionShell.BASH: render_bash,
        CompletionShell.ZSH: render_zsh,
        CompletionShell.FISH: render_fish,
        CompletionShell.POWERSHELL: render_powershell,
    }
    return renderers[shell](command_name=command_name, launcher=launcher)
