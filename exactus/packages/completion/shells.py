"""Shell registration-script renderers.

Each generated script is a thin transport adapter: it captures the
shell's completion context, invokes ``exactus __complete`` with the
normalized request, and maps the returned Unit-Separated records onto
native completion primitives. No CLI semantics live in shell code.

Generated output is deterministic for a fixed ``command_name`` and
``launcher`` and carries a protocol-version marker so stale installs
can be diagnosed.
"""

from __future__ import annotations

from re import sub
from shlex import quote
from typing import Final

from .model import CompletionShell
from .protocol import Constants


def function_name(*, command_name: str) -> str:
    """Sanitize a command name into a shell function identifier.

    Args:
        command_name: Registered command name.

    Returns:
        Identifier containing only letters, digits and underscores.

    """
    cleaned: str = sub(pattern="[^a-zA-Z0-9_]", repl="_", string=command_name)
    return f"_{cleaned.lstrip('_') or 'tool'}_completion"


def _bash_launcher(*, launcher: tuple[str, ...]) -> str:
    """Quote a launcher argv for POSIX-family shells.

    Args:
        launcher: Executable and fixed arguments.

    Returns:
        Shell-quoted invocation fragment.

    """
    return " ".join(quote(s=word) for word in launcher)


def _powershell_quote(*, word: str) -> str:
    """Quote one argument for PowerShell.

    Args:
        word: Argument text.

    Returns:
        Single-quoted literal.

    """
    return "'" + word.replace("'", "''") + "'"


def _powershell_launcher(*, launcher: tuple[str, ...]) -> str:
    """Render a PowerShell invocation of the launcher.

    Args:
        launcher: Executable and fixed arguments.

    Returns:
        ``& 'exe' 'arg' ...`` fragment.

    """
    return "& " + " ".join(_powershell_quote(word=word) for word in launcher)


def _marker(*, shell: CompletionShell, command_name: str) -> str:
    """Render the deterministic script marker header.

    Args:
        shell: Target shell.
        command_name: Registered command name.

    Returns:
        Comment lines identifying the generator and protocol.

    """
    return f"""\
# Generated by {command_name}.
# Completion protocol: {Constants.protocol_version}
# Regenerate with: {command_name} completion {shell.value}
"""


def render_bash(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the Bash registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        Source-able Bash completion code.

    """
    function: str = function_name(command_name=command_name)
    invoke: str = _bash_launcher(launcher=launcher)
    marker: str = _marker(
        shell=CompletionShell.BASH,
        command_name=command_name,
    )
    return f"""\
{marker}{function}() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}"
    local -a request=(
        "__complete"
        "--protocol-version={Constants.protocol_version}"
        "--shell=bash"
        "--active-word-index=${{COMP_CWORD}}"
        "--prefix=${{cur}}"
    )
    local word
    for word in "${{COMP_WORDS[@]}}"; do
        request+=("--word=${{word}}")
    done
    COMPREPLY=()
    local line value display description kind flags
    local nospace=0
    while IFS= read -r line; do
        IFS=$'\\x1f' read -r value display description kind flags \\
            <<< "${{line}}"
        COMPREPLY+=("${{value}}")
        flags="${{flags:-0}}"
        if (( (10#${{flags}} & 1) == 0 )); then
            nospace=1
        fi
    done < <(command {invoke} "${{request[@]}}" 2>/dev/null)
    if (( nospace )); then
        compopt -o nospace
    fi
}}
complete -F {function} {quote(s=command_name)}
"""


def render_zsh(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the Zsh registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        Zsh completion code usable with ``compdef``.

    """
    function: str = function_name(command_name=command_name)
    invoke: str = _bash_launcher(launcher=launcher)
    return f"""\
#compdef {command_name}
{_marker(shell=CompletionShell.ZSH, command_name=command_name)}{function}() \
{{
    local -a request spaced spaced_desc nospace nospace_desc lines fields
    local line value display description kind flags
    request=(
        "__complete"
        "--protocol-version={Constants.protocol_version}"
        "--shell=zsh"
        "--active-word-index=$((CURRENT - 1))"
        "--prefix=${{PREFIX}}"
    )
    local word
    for word in "${{words[@]}}"; do
        request+=("--word=${{word}}")
    done
    lines=("${{(@f)$(command {invoke} "${{request[@]}}" 2>/dev/null)}}")
    for line in "${{lines[@]}}"; do
        fields=()
        IFS=$'\\x1f' read -rA fields <<< "${{line}}"
        value="${{fields[1]}}"
        display="${{fields[2]}}"
        description="${{fields[3]}}"
        flags="${{fields[5]:-0}}"
        if (( (10#${{flags}} & 1) == 0 )); then
            nospace+=("${{value}}")
            nospace_desc+=("${{description}}")
        else
            spaced+=("${{value}}")
            spaced_desc+=("${{description}}")
        fi
    done
    (( ${{#spaced[@]}} )) && \\
        compadd -Q -d spaced_desc -S ' ' -- "${{spaced[@]}}"
    (( ${{#nospace[@]}} )) && \\
        compadd -Q -d nospace_desc -S '' -- "${{nospace[@]}}"
    return 0
}}
compdef {function} {quote(s=command_name)}
"""


def _fish_quote(*, word: str) -> str:
    """Quote a Fish argument without POSIX quote concatenation.

    Args:
        word: Literal argument.

    Returns:
        Safely quoted shell text.

    """
    if word and all(char.isalnum() or char in "_./-" for char in word):
        return word
    return "'" + word.replace("\\", "\\\\").replace("'", "\\'") + "'"


def render_fish(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the Fish registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        Fish completion code usable with ``complete``.

    """
    registered: str = _fish_quote(word=command_name)
    function: str = function_name(command_name=command_name)
    invoke: str = " ".join(_fish_quote(word=word) for word in launcher)
    marker: str = _marker(
        shell=CompletionShell.FISH,
        command_name=command_name,
    )
    return f"""\
{marker}function {function}
    set -l us (printf '\\x1f')
    set -l prior (commandline -opc)
    set -l active (commandline -ct)
    set -l request \\
        __complete \\
        --protocol-version={Constants.protocol_version} \\
        --shell=fish \\
        --active-word-index=(count $prior) \\
        --prefix=$active
    for word in $prior
        set -a request --word=$word
    end
    set -a request --word=$active
    for line in (command {invoke} $request 2>/dev/null)
        set -l fields (string split -- $us $line)
        set -l value $fields[1]
        set -l description ""
        if test (count $fields) -ge 3
            set description $fields[3]
        end
        if test -n "$description"
            printf '%s\\t%s\\n' $value $description
        else
            printf '%s\\n' $value
        end
    end
end
complete --command {registered} --no-files --arguments '({function})'
"""


def render_powershell(*, command_name: str, launcher: tuple[str, ...]) -> str:
    """Render the PowerShell registration script.

    Args:
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        PowerShell completion code using the native argument completer.

    """
    invoke: str = _powershell_launcher(launcher=launcher)
    marker: str = _marker(
        shell=CompletionShell.POWERSHELL,
        command_name=command_name,
    )
    quoted_name: str = _powershell_quote(word=command_name)
    variable: str = command_name.replace("-", "_")
    return f"""\
{marker}$__{variable}Completer = {{
    param(
        $wordToComplete,
        $commandAst,
        $cursorPosition
    )
    $words = [System.Collections.Generic.List[string]]::new()
    $prefix = ''
    $hasActive = $false
    foreach ($element in $commandAst.CommandElements) {{
        if ($element.Extent.StartOffset -gt $cursorPosition) {{ break }}
        $raw = $element.Extent.Text
        $isActive = $element.Extent.EndOffset -ge $cursorPosition
        if ($isActive) {{
            $length = $cursorPosition - $element.Extent.StartOffset
            $raw = $raw.Substring(0, [Math]::Min($raw.Length, $length))
        }}
        $tokens = $null
        $parseErrors = $null
        $parsed = [System.Management.Automation.Language.Parser]\
::ParseInput(
            $raw, [ref]$tokens, [ref]$parseErrors
        )
        $string = $parsed.Find({{
            param($node)
            $node.GetType().Name -in @(
                'StringConstantExpressionAst',
                'ExpandableStringExpressionAst'
            )
        }}, $true)
        $quoted = $raw.StartsWith("'") -or $raw.StartsWith('"')
        $value = if (
            $null -ne $string -and ($quoted -or $raw.Contains('`'))
        ) {{ $string.Value }} else {{ $raw }}
        $words.Add($value)
        if ($isActive) {{
            $prefix = $value
            $hasActive = $true
            break
        }}
    }}
    if (-not $hasActive) {{ $words.Add('') }}
    $request = [System.Collections.Generic.List[string]]::new()
    $request.Add('__complete')
    $request.Add('--protocol-version={Constants.protocol_version}')
    $request.Add('--shell=powershell')
    $request.Add("--active-word-index=$($words.Count - 1)")
    $request.Add("--prefix=$prefix")
    foreach ($word in $words) {{
        $request.Add("--word=$word")
    }}
    $output = {invoke} @request 2>$null
    foreach ($line in $output) {{
        $fields = $line -split [char]0x1f, 5
        if ($fields.Count -lt 5) {{ continue }}
        $type = 'ParameterValue'
        switch ($fields[3]) {{
            'command'   {{ $type = 'Command' }}
            'option'    {{ $type = 'ParameterName' }}
            'file'      {{ $type = 'ProviderItem' }}
            'directory' {{ $type = 'ProviderContainer' }}
        }}
        [System.Management.Automation.CompletionResult]::new(
            $fields[0],
            $fields[1],
            $type,
            $fields[2]
        )
    }}
}}
Register-ArgumentCompleter -Native `
    -CommandName {quoted_name} `
    -ScriptBlock $__{variable}Completer
"""


def render(
    *,
    shell: CompletionShell,
    command_name: str,
    launcher: tuple[str, ...],
) -> str:
    """Dispatch to the shell-specific renderer.

    Args:
        shell: Target shell.
        command_name: Registered command name.
        launcher: Executable and fixed arguments invoked for
            completion.

    Returns:
        The registration script.

    """
    renderers: Final = {
        CompletionShell.BASH: render_bash,
        CompletionShell.ZSH: render_zsh,
        CompletionShell.FISH: render_fish,
        CompletionShell.POWERSHELL: render_powershell,
    }
    return renderers[shell](command_name=command_name, launcher=launcher)
