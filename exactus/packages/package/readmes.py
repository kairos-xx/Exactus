"""Generate directory documentation for offline distribution assets."""

from __future__ import annotations

from typing import TYPE_CHECKING

from exactus.tools.common.directory_inventory import heal_directory

if TYPE_CHECKING:
    from pathlib import Path


def directory_readme(*, name: str) -> str:
    """Describe one generated asset directory.

    Args:
        name: Directory basename.

    Returns:
        Markdown documentation for the directory.

    """
    descriptions: dict[str, str] = {
        "data": "Bundle metadata, measurements, and partitioned payloads.",
        "parts": "Payload filesystem and build activity records.",
        "fs": "Filesystem catalog, immutable packs, and retained catalogs.",
        "catalogs": "Retained catalogs for incremental updates and rollback.",
        "packs": "Content-addressed compressed packs grouped by hash prefix.",
    }
    description: str = descriptions.get(
        name,
        "Immutable compressed payload packs for this hash prefix.",
    )
    return (
        f"# `{name}/`\n\n{description}\n\n"
        "Generated by the offline bundle builder. Keep these assets with "
        "the package; normal runs preserve existing packs and catalogs.\n"
    )


def write_directory_readmes(*, root: Path) -> None:
    """Document public asset directories while preserving existing docs.

    Args:
        root: Generated asset subtree.

    """
    if not root.is_dir() or root.is_symlink():
        return
    readme: Path = root / "README.md"
    if not readme.exists():
        _ = readme.write_text(
            data=directory_readme(
                name="fs" if (root / "catalog.json").is_file() else root.name,
            ),
            encoding="utf-8",
        )
    for child in sorted(root.iterdir()):
        if not child.name.startswith(".") and child.name != "__pycache__":
            write_directory_readmes(root=child)
    heal_directory(
        directory=root,
        entries=[
            entry
            for entry in sorted(root.iterdir())
            if not entry.name.startswith(".") and entry.name != "__pycache__"
        ],
    )
